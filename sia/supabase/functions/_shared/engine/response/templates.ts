export const PACKS: Record<Lang, Pack> = { en, fr, ar, derja }

/** Looks a template up in the chosen language, falling back to English when a pack lacks the key. */
export function template(lang: Lang, key: string): string | undefined {
  return PACKS[lang][key] ?? en[key]
}

export function fill(tpl: string, params: Record<string, string> = {}): string {
  return tpl.replace(/\{([a-z_]+)\}/g, (_m, k: string) => params[k] ?? '')
}
